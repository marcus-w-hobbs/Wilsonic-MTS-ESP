#!/usr/bin/env bash
# Shared helpers for set-version.sh and check-version.sh. Source, do not run.
# Compatible with bash 3.2 (macOS) and bash 5 (CI).

# Repo root. WILSONIC_ROOT overrides it so tests can run on a sandbox copy.
version_root() {
    if [ -n "${WILSONIC_ROOT:-}" ]; then
        echo "$WILSONIC_ROOT"
    else
        dirname "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    fi
}

# Semver: MAJOR.MINOR.PATCH with an optional -PRERELEASE suffix.
# The suffix may hold letters, digits, dots and hyphens, and must not be empty.
version_is_valid() {
    printf '%s' "$1" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$'
}

# Split "1.2.3-beta" into globals: V_MAJOR V_MINOR V_PATCH V_PRE V_CORE V_HINT V_BETA
version_parse() {
    local v="$1"
    V_CORE="${v%%-*}"
    if [ "$V_CORE" = "$v" ]; then V_PRE=""; else V_PRE="${v#*-}"; fi
    V_MAJOR="${V_CORE%%.*}"
    local rest="${V_CORE#*.}"
    V_MINOR="${rest%%.*}"
    V_PATCH="${rest#*.}"
    # VERSION_HINT feeds JUCE ParameterID version hints and must only increase.
    # major*1000+minor equals the historical value (minor alone) for 0.x.
    V_HINT=$((10#$V_MAJOR * 1000 + 10#$V_MINOR))
    if [ -n "$V_PRE" ]; then V_BETA=1; else V_BETA=0; fi
}

# Render version.h for the parsed version. VER_NUM stays a numeric literal
# (major.minor) because AppVersion.h passes it through std::to_string.
version_render_header() {
    cat <<HDR
// Generated by scripts/set-version.sh from the VERSION.txt file. Do not edit.
// Change VERSION.txt, then run scripts/set-version.sh.
#define VERSION_MAJOR $V_MAJOR
#define VERSION_MINOR $V_MINOR
#define VERSION_PATCH $V_PATCH
#define VER_NUM $V_MAJOR.$V_MINOR
#define BETA $V_BETA
#define VERSION_HINT $V_HINT
#define VERSION_STRING "$V_MAJOR.$V_MINOR.$V_PATCH${V_PRE:+-$V_PRE}"
HDR
}

# Read a #define value from a header.
version_macro() { # file NAME
    sed -n "s/^#define $2 //p" "$1" | head -1
}

# Read the project version attribute from a .jucer (three-part only, so the
# XML declaration's version="1.0" is never matched).
version_jucer() { # file
    sed -n 's/.* version="\([0-9][0-9]*\.[0-9][0-9]*\.[0-9][0-9]*\)".*/\1/p' "$1" | head -1
}
